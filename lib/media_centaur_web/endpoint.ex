defmodule MediaCentaurWeb.Endpoint do
  @moduledoc false
  use Phoenix.Endpoint, otp_app: :media_centaur

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_media_centaur_key",
    signing_salt: "skK1Dh/W",
    same_site: "Lax"
  ]

  # `:peer_data` so `Live.PlayerAware` can judge the socket's address the
  # way `Plugs.RemoteAccess` judges a request's.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  #
  # Ahead of the gate: the bundle is public, and the pairing page needs it.
  plug Plug.Static,
    at: "/",
    from: :media_centaur,
    gzip: not code_reloading?,
    only: MediaCentaurWeb.static_paths(),
    cache_control_for_vsn_requests: "public, max-age=31536000, immutable",
    cache_control_for_etags: "public, max-age=3600"

  # The gate: a request from the host passes; one from the LAN passes only
  # with a paired player in its session (`MediaCentaurWeb.RemoteAccess`).
  # Session first so the gate can read it; the gate ahead of `ImageServer`
  # so artwork is behind it too.
  plug Plug.Session, @session_options
  plug MediaCentaurWeb.Plugs.RemoteAccess

  plug MediaCentaurWeb.Plugs.ImageServer

  # Tidewave MCP — must be before code_reloading? block per Tidewave docs.
  if Code.ensure_loaded?(Tidewave) do
    # toolbar: false — Tidewave 0.9 injects a browser toolbar by default; the
    # MCP endpoint is all we use.
    plug Tidewave, toolbar: false
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :media_centaur
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug MediaCentaurWeb.Router
end
